"""
Tests for the PeachPy backend and the user-facing JIT matmul API.

Three levels of verification:

* :func:`test_encode_matches_reference` -- the primary gate, runs on any host (including this
  arm64 Mac). For each committed golden under ``tests/filecheck/libxsmm/``, it encodes the
  kernel to machine code, disassembles it, and asserts the computational instruction stream
  matches the reference Intel-syntax assembly (the same text produced by ``xdsl-opt … -t
  x86-asm``). Stack-framing instructions (``push``/``pop``/``vzeroupper``) are dropped from both
  sides: xDSL's prologue-epilogue pass and PeachPy's ``finalize`` save the same callee-saved
  registers but in a different order, and PeachPy adds a ``vzeroupper``.
* :func:`test_execution` -- runs only on an x86-64 CPU with AVX-512 (``skipif`` otherwise,
  since executing the kernel elsewhere SIGILLs). Loads the raw column-major ``16x3x5`` kernel
  and checks the numerical result against a NumPy reference.
* :func:`test_jit_matmul` -- same guard. Exercises the row-major
  :mod:`autotuner.libxsmm_gemm.jit` API across several small shapes (incl. masked and
  memory-broadcast microkernels).
"""

from __future__ import annotations

import re
from pathlib import Path

import capstone
import pytest
from peachpy.x86_64 import abi

from autotuner.libxsmm_gemm.jit import is_available
from autotuner.libxsmm_gemm.libxsmm_cpuid import Arch
from autotuner.libxsmm_gemm.libxsmm_macros import gemm_flags
from autotuner.libxsmm_gemm.libxsmm_main import DescDatatype, GEMMDescriptor, GEMMFlag
from autotuner.libxsmm_gemm.libxsmm_typedefs import Datatype
from autotuner.libxsmm_gemm.peachpy_backend import build_callable, build_function

# Executing the AVX-512 kernels requires an x86-64 CPU with AVX-512 (else SIGILL, which is
# uncatchable). `skipif` -- not `xfail` -- because xfail still *runs* the test body.
_requires_avx512 = pytest.mark.skipif(
    not is_available(), reason="requires an x86-64 CPU with AVX-512"
)

_FILECHECK_DIR = Path(__file__).parent / "filecheck" / "libxsmm"

# Committed golden asm files (generated by the RUN line each contains). Covers the three DP
# microkernels: register-broadcast (16x3x5), memory-broadcast/rsm (8x8x8), and masked (4x4x4).
_GOLDENS = ["16x3x5_skx_dp.mlir", "8x8x8_skx_dp.mlir", "4x4x4_skx_dp.mlir"]

# Stack-framing mnemonics dropped from both instruction streams before comparison.
_FRAMING = {"push", "pop", "vzeroupper"}


def _desc_from_runline(path: Path) -> tuple[str, GEMMDescriptor]:
    """Build the ``(routine_name, GEMMDescriptor)`` a golden file's RUN line describes.

    RUN args after ``libxsmm-gemm dense %t``:
    ``routine m n k lda ldb ldc alpha beta align_a align_c arch prefetch precision``.
    """
    run = next(line for line in path.read_text().splitlines() if "libxsmm-gemm" in line)
    tokens = run.split("libxsmm-gemm dense %t ", 1)[1].split("&&")[0].split()
    routine = tokens[0]
    m, n, k, lda, ldb, ldc, _alpha, beta, align_a, align_c = map(int, tokens[1:11])
    precision = tokens[13]

    dt = Datatype.F64 if precision == "DP" else Datatype.F32
    flags = gemm_flags("N", "N")
    if beta == 0:
        flags |= GEMMFlag.BETA_0
    if align_a:
        flags |= GEMMFlag.ALIGN_A
    if align_c:
        flags |= GEMMFlag.ALIGN_C

    desc = GEMMDescriptor(
        m=m,
        n=n,
        k=k,
        lda=lda,
        ldb=ldb,
        ldc=ldc,
        datatype=DescDatatype(dt, dt, dt, dt),
        flags=flags,
        prefetch="nopf",
    )
    return routine, desc


# region: assembly normalization


def _canon_int(token: str) -> int:
    """Parse a decimal/hex token as a signed 64-bit integer (capstone prints two's
    complement, e.g. ``0xffffffffffffffc0`` for ``-64``)."""
    value = int(token, 0)
    if value >= 2**63:
        value -= 2**64
    return value


def _canon_operand(operand: str) -> str:
    """Canonicalize a single operand so capstone's and the reference's spelling agree: strip
    ``zmmword ptr`` size hints, normalize hex-vs-decimal and spacing, and re-attach EVEX
    decorations (``{k1}``, ``{z}``, ``{1to8}``) with internal spaces removed."""
    operand = operand.strip().lower()
    operand = re.sub(r"^\w+ ptr ", "", operand)  # drop capstone's operand-size hint

    # Peel off EVEX decorations (mask / zeroing / broadcast), regardless of spacing.
    decorations = "".join(d.replace(" ", "") for d in re.findall(r"\{[^}]*\}", operand))
    base = re.sub(r"\s*\{[^}]*\}", "", operand).strip()

    if base.startswith("["):
        inner = base[1:-1].strip()
        match = re.fullmatch(r"(\w+)\s*([+-]\s*(?:0x[0-9a-f]+|\d+))?", inner)
        assert match is not None, f"unparsed memory operand: {operand!r}"
        reg = match.group(1)
        offset = match.group(2)
        if offset and (value := _canon_int(offset.replace(" ", ""))):
            core = f"[{reg}{value:+d}]"
        else:
            core = f"[{reg}]"
    elif re.fullmatch(r"[a-z][a-z0-9]*", base):
        core = base  # a register name
    else:
        core = str(_canon_int(base))  # an immediate

    return core + decorations


def _canon_instruction(mnemonic: str, operands: str) -> str:
    mnemonic = mnemonic.strip().lower()
    operands = operands.strip().lower()
    if mnemonic.startswith("j"):
        # Jump target is a label in the reference but an absolute address in capstone's
        # output; canonicalize so the comparison checks mnemonic + presence, not the target
        # spelling (loop structure is guaranteed by the IR verifiers).
        return f"{mnemonic} <target>"
    if not operands:
        return mnemonic
    canon = ",".join(_canon_operand(part) for part in operands.split(","))
    return f"{mnemonic} {canon}"


def _reference_instructions(path: Path) -> list[str]:
    """The normalized computational instruction stream from a golden's ``// CHECK`` lines."""
    instructions: list[str] = []
    for line in path.read_text().splitlines():
        # Only the first RUN block's plain `CHECK`/`CHECK-NEXT` lines match; a
        # `CHECK-IR-LIBXSMM` IR-check block (if any) uses a different prefix and is ignored.
        match = re.match(r"^//\s*CHECK(?:-NEXT)?:\s*(.*)$", line)
        if match is None:
            continue
        text = match.group(1).strip()
        mnemonic, _, operands = text.partition(" ")
        if not text or text.startswith(".") or text.endswith(":"):
            # Skip directives (.text, .globl, …) and label definitions (matmul_bac:, l33:).
            continue
        if mnemonic in _FRAMING:
            continue
        instructions.append(_canon_instruction(mnemonic, operands))
    return instructions


def _encoded_instructions(routine: str, desc: GEMMDescriptor) -> list[str]:
    """The normalized computational instruction stream of the PeachPy-encoded kernel.

    ``build_function`` returns an un-finalized ``Function`` on any host; we finalize with the
    explicit System V ABI object to obtain the byte stream (``abi.detect()`` is ``None`` on a
    non-x86 interpreter)."""
    function = build_function(routine, desc, Arch.LIBXSMM_X86_AVX512_SKX)
    code = bytes(
        function.finalize(abi.system_v_x86_64_abi).encode().code_section.content
    )

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.syntax = capstone.CS_OPT_SYNTAX_INTEL
    return [
        _canon_instruction(insn.mnemonic, insn.op_str)
        for insn in md.disasm(code, 0)
        if insn.mnemonic not in _FRAMING
    ]


# endregion


@pytest.mark.parametrize("golden", _GOLDENS)
def test_encode_matches_reference(golden: str):
    path = _FILECHECK_DIR / golden
    routine, desc = _desc_from_runline(path)
    assert _encoded_instructions(routine, desc) == _reference_instructions(path)


@_requires_avx512
def test_execution():
    import ctypes

    import numpy as np

    # The committed 16x3x5 aligned column-major kernel (raw backend, no row-major swap).
    _, desc = _desc_from_runline(_FILECHECK_DIR / "16x3x5_skx_dp.mlir")
    m, n, k = desc.m, desc.n, desc.k
    kernel = build_callable("matmul_bac", desc, Arch.LIBXSMM_X86_AVX512_SKX)
    rng = np.random.default_rng(0)

    def aligned(shape, alignment=64):
        """A 64-byte-aligned column-major (Fortran-order) float64 array of random data.

        The aligned ``vmovapd`` loads/stores of A and C require 64-byte alignment; B is only
        read via ``vbroadcastsd`` and has no alignment requirement, but we align it too.

        We over-allocate a byte buffer, slice at the first aligned offset, and reshape as a
        *view* (Fortran order) -- never ``asfortranarray``, which would copy into a fresh,
        unaligned buffer. The assertion guards against any accidental copy."""
        count = int(np.prod(shape))
        buf = np.empty(count * 8 + alignment, dtype=np.uint8)
        offset = (-buf.ctypes.data) % alignment
        arr = (
            buf[offset : offset + count * 8].view(np.float64).reshape(shape, order="F")
        )
        assert arr.ctypes.data % alignment == 0
        arr[...] = rng.random(count).reshape(shape, order="F")
        return arr

    # Roles read off the IR: rdi (arg0) feeds the vmovapd A-loads, rsi (arg1) the
    # vbroadcastsd B-scalars, rdx (arg2) the C accumulators. All column-major:
    # C[M,N] += A[M,K] @ B[K,N] with lda=M, ldb=K, ldc=M (see ref_matmul_colmaj).
    a = aligned((m, k))
    b = aligned((k, n))
    c = aligned((m, n))

    expected = c + a @ b

    # PeachPy loads the kernel with ctypes argtypes POINTER(c_double) (from the ptr(double_)
    # arguments), which rejects c_void_p / plain ints -- pass typed pointers.
    ptr_double = ctypes.POINTER(ctypes.c_double)
    kernel(
        a.ctypes.data_as(ptr_double),
        b.ctypes.data_as(ptr_double),
        c.ctypes.data_as(ptr_double),
    )

    assert np.allclose(c, expected)


@_requires_avx512
@pytest.mark.parametrize(
    "m,n,k",
    [(16, 3, 5), (8, 8, 8), (4, 4, 4), (6, 7, 3), (1, 1, 1), (2, 10, 7)],
)
def test_jit_matmul(m: int, n: int, k: int):
    import numpy as np

    from autotuner.libxsmm_gemm.jit import jit_matmul, matmul

    rng = np.random.default_rng(0)
    a = rng.random((m, k))
    b = rng.random((k, n))

    # Fresh result C = A @ B.
    assert np.allclose(matmul(a, b), a @ b)

    # In-place accumulate: out += A @ B, returning the same array.
    out = rng.random((m, n))
    expected = out + a @ b
    result = jit_matmul(m, n, k)(a, b, out)
    assert result is out
    assert np.allclose(out, expected)
